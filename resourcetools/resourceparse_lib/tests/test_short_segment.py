"""
Regression test: a segment shorter than its adb layout is parsed up to its
end, whatever kind of field - enum, union selector, condition variable -
the layout places past that end.

Usage:
    python3 test_short_segment.py
"""

import os
import shutil
import subprocess
import sys
import tempfile
import unittest

TESTS_DIR = os.path.dirname(os.path.abspath(__file__))
RESOURCETOOLS_DIR = os.path.dirname(os.path.dirname(TESTS_DIR))
SRC_DIR = os.path.dirname(RESOURCETOOLS_DIR)
COMMON_DIR = os.path.join(SRC_DIR, "common")


class ShortSegmentTest(unittest.TestCase):

    @classmethod
    def setUpClass(cls):
        # tools_version.py is generated by configure; an unconfigured tree gets the template
        cls._version_dir = tempfile.mkdtemp()
        shutil.copy(os.path.join(COMMON_DIR, "tools_version.py.in"), os.path.join(cls._version_dir, "tools_version.py"))

    @classmethod
    def tearDownClass(cls):
        shutil.rmtree(cls._version_dir)

    def _run_parse(self, dump_name, adb_name):
        env = dict(os.environ)
        env["PYTHONPATH"] = os.pathsep.join([RESOURCETOOLS_DIR, COMMON_DIR, self._version_dir])
        return subprocess.run([sys.executable, os.path.join(RESOURCETOOLS_DIR, "mstresourceparse.py"),
                               "-d", os.path.join(TESTS_DIR, dump_name),
                               "-a", os.path.join(TESTS_DIR, adb_name)],
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT, universal_newlines=True, env=env)

    def test_fields_past_the_end_of_a_short_segment(self):
        result = self._run_parse("short_segment.dump", "short_segment.adb")
        self.assertEqual(result.returncode, 0, result.stdout)
        self.assertIn("doesn't match the adb segment size", result.stdout)
        self.assertIn("plain_field = 0x12345678", result.stdout)
        self.assertIn("opt_field = 0x1", result.stdout)
        # the fields past the end of the segment are left out, as a plain field is
        self.assertNotIn("kind", result.stdout.replace('"$(parent).kind"', ""))
        self.assertNotIn("payload", result.stdout)

    def test_be_arrays_still_parsed(self):
        result = self._run_parse("be_arrays.dump", "be_arrays.adb")
        self.assertEqual(result.returncode, 0, result.stdout)
        self.assertIn("regular_field1 = 0x12345678", result.stdout)


if __name__ == "__main__":
    unittest.main()
